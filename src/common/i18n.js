export function makeT(lang) {
  const dict = DICT[lang] || DICT.en;
  function t(key, params) {
    let s = dict[key] != null ? dict[key] : (DICT.en[key] != null ? DICT.en[key] : key);
    if (params) {
      for (const k in params) s = s.split('{' + k + '}').join(String(params[k]));
    }
    return s;
  }
  t.lang = lang;
  return t;
}
